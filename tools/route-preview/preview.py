#!/usr/bin/env python3
"""Render the world-view route OUT OF GAME, to a PNG.

WHY THIS EXISTS. Every look decision on the route -- feather, halo weight, the near
fade, opacity, colour -- has so far cost a launch, a load, a walk to a quest giver and
a squint. That loop is minutes long and the thing being judged is a few dozen pixels,
so the comparisons that matter (this feather against that one, side by side, on the
same ground) were never actually made: each session judged one setting against a
memory of the last.

This draws the same sprites the game draws, from the same textures and the same
constants, onto a synthetic floor. It is a LOOK tool, not a correctness tool -- the
harnesses (tools/nav-harness, tools/route-harness) own behaviour, and nothing here
should ever be used to decide whether the route is right, only whether it reads.

WHAT IS REPRODUCED EXACTLY, because it is read from the source rather than retyped:

  * every RTE constant (opacity, colour, widths, feather pad, halo, fades, clamps) is
    parsed out of gamedata/scripts/iqm_core.script at run time;
  * the vertex spacing rules (SEG_DIV / SEG_MIN / SEG_MAX / TURN_TOL) are parsed out
    of iqm_nav.script;
  * the TEXTURES are generated by importing tools/stroke-tex/build.py and calling its
    own alpha functions, so the artwork is the shipped artwork -- and `--feather`
    re-runs them at a different value without touching the shipped assets, which is
    the whole point of the tool;
  * the drawing rules are ported line for line from IqmCards: seg_width measures the
    thickness from the segment's own projected ground edges, place_strip builds the
    rect in UI units and rotate-then-uniform-scales it, the halo is the same texture
    at a larger rect, and everything is composited far to near in the same order.

WHAT IS AN APPROXIMATION, stated plainly so nothing is read off this that shouldn't be:

  * THE PROJECTION. The game calls game.world2ui_with_depth (engine side, and it takes
    the player's actual FOV); this is a pinhole camera at --fov degrees vertical. So
    absolute on-screen sizes depend on a number we are assuming. RELATIVE judgements --
    is this edge softer than that one, does the near mark dominate -- do not.
  * THE FLOOR is procedural concrete, not a level. It exists to have something to be
    legible against, and carries a light patch and a dark one on purpose, because the
    route has to work on both.
  * FILTERING. PIL's bilinear resample where the GPU has its own; at these scales the
    difference is well under the effects being judged.
  * No occlusion. Every point is drawn lit, as if nothing were in the way.

Usage:
    python preview.py                          # default look, band style
    python preview.py --style arrows --scene bend
    python preview.py --compare                # current vs the sharpened proposal
    python preview.py --feather 0.04 --hmin 0.75 --head 1.5 --alpha 255
    python preview.py --dump                   # print every parsed constant and exit

Requires Pillow. Run from anywhere; paths are resolved off this file.
"""
import argparse
import importlib.util
import math
import os
import random
import re
import sys

from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
MARKERS = os.path.join(ROOT, "gamedata", "scripts", "iqm_core.script")
NAV = os.path.join(ROOT, "gamedata", "scripts", "iqm_nav.script")
STROKE_TEX = os.path.join(ROOT, "tools", "stroke-tex", "build.py")

# The virtual UI space every static is placed in -- the same 1024x768 the mod uses.
UI_W, UI_H = 1024, 768

# How much of a segment's own LENGTH the joint overlap may take, under --joint capped.
# A bend of angle t needs about (th/2) * tan(t/2) of extension to close its wedge, and
# iqm_nav sizes segments so consecutive ones turn by ~1/7 radian -- about 4% of a
# half-thickness. So a third of the segment is still enormously over-provisioned, and
# far enough from the shipped `th` at the near end to show whether the ladder is really
# the overlap.
JOINT_FRAC = 0.35


# --------------------------------------------------------------------------
# Reading the real constants
# --------------------------------------------------------------------------
# Parsed rather than copied. A preview whose numbers have drifted from the game's is
# worse than no preview at all: it answers confidently and wrongly, and nothing about
# the picture says which constants it used. --dump prints them for the same reason.
# Only what the one surviving design uses. The stroke's and the billboard's constants
# (ww, bandw, SEGS, REF, MIN, MAX, HALO...) went with the four styles dropped in R2.26c.
RTE_KEYS = """a r g b alen awide aw FPAD WMIN WMAX MCAP EDGE EDGE_MIN EDGE_MAX SHA
              HEAD HMIN MNEAR MFADE MLMIN PPM FADE TAIL""".split()

NAV_KEYS = ["SEG_DIV", "SEG_MIN", "SEG_MAX", "TURN_TOL", "PATH_STEP", "ARROW_LIFT",
            "NEAR_TRIM", "TRIM_FRAC", "MAX_DRAW", "MAX_CHEV", "CHEV_DIR"]


def _read(path):
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        return fh.read()


def parse_rte():
    """Pull the RTE table's numeric fields out of iqm_core.script.

    Whitelisted by name rather than taken wholesale: the table also holds NAMES,
    the CLIP grid and the t1/t2 scratch points, and a blind `key = number` sweep
    would pick up `x = 0, y = 0, z = 0` from the scratch and call it geometry.
    """
    src = _read(MARKERS)
    start = src.index("local RTE = {")
    # To the table's own closing brace, not a fixed byte count. A 12000-char window was
    # enough until R2.31's comment pushed PPM past it, and the failure was a preview that
    # could not start rather than one that quietly read the wrong number -- but only by
    # luck, since the window's far end lands wherever the prose happens to reach.
    end = src.find("\n}", start)
    body = src[start:end if end > start else start + 20000]
    out = {}
    for key in RTE_KEYS:
        m = re.search(r"\b" + key + r"\s*=\s*(-?\d[\d.]*)", body)
        if not m:
            raise SystemExit("preview: could not find RTE.%s in iqm_core.script" % key)
        out[key] = float(m.group(1))
    # The MCM default colour, which read_config pushes over RTE's own initialiser. The
    # table in RTE is the fallback for a missing option, not what the player sees.
    for key in ("route_r", "route_g", "route_b", "route_a", "route_w", "route_gap",
                "route_size"):
        m = re.search(r"\b" + key + r"\s*=\s*(\d+)", src[:20000])
        if m:
            out[key] = float(m.group(1))
    return out


def parse_nav():
    src = _read(NAV)
    out = {}
    for key in NAV_KEYS:
        m = re.search(r"^local " + key + r"\s*=\s*(-?\d[\d.]*)", src, re.M)
        if not m:
            raise SystemExit("preview: could not find %s in iqm_nav.script" % key)
        out[key] = float(m.group(1))
    return out


def load_builder():
    """Import tools/stroke-tex/build.py for its alpha functions.

    Importing rather than reimplementing: `across`, `along` and `mark_alpha` ARE the
    artwork, and a second copy of them here would be a second thing to keep in step.
    Safe to import -- everything that shells out to ImageMagick is inside main().
    """
    spec = importlib.util.spec_from_file_location("iqm_stroke_build", STROKE_TEX)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    # Snapshot the SHIPPED values before anything renders. tex_strip/tex_mark set
    # mod.FEATHER to whatever is being previewed -- that is how --feather works -- so
    # after the first render the module no longer knows what the assets on disk were.
    # Reading it back later is how the comparison sheet first labelled the CURRENT panel
    # with the PROPOSED feather, which is the one mistake a look tool must not make.
    mod.SHIPPED = {"FEATHER": mod.FEATHER, "ARM_TIP": mod.ARM_TIP, "ARM_TAIL": mod.ARM_TAIL}
    return mod


# --------------------------------------------------------------------------
# Textures
# --------------------------------------------------------------------------
def tex_strip(bp, feather, tip=0.0, tail=0.0):
    """iqm_stroke / iqm_arm, at an arbitrary feather. Mirrors build.build()."""
    bp.FEATHER = feather
    w, h = bp.W, bp.H
    img = Image.new("RGBA", (w, h), (255, 255, 255, 0))
    px = img.load()
    for y in range(h):
        c = bp.across(y)
        for x in range(w):
            px[x, y] = (255, 255, 255, int(round(255 * c * bp.along(x, tip, tail))))
    return img


def tex_mark(bp, feather, size=192):
    """iqm_mark, at an arbitrary feather. Mirrors build.build_mark()."""
    bp.FEATHER = feather
    x0, x1, y0, y1 = bp.mark_box()
    hl, hw, ha = bp.MARK_LEN * 0.5, bp.MARK_WIDE * 0.5, bp.MARK_ARM * 0.5
    pad = feather * bp.MARK_ARM
    img = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    px = img.load()
    for j in range(size):
        yy = y0 + (j + 0.5) / size * (y1 - y0)
        for i in range(size):
            xx = x0 + (i + 0.5) / size * (x1 - x0)
            av, ink = bp.mark_alpha(xx, yy, hl, hw, ha, pad, want_ink=True)
            v = int(round(255 * ink))
            px[i, j] = (v, v, v, int(round(255 * av)))
    return img


# --------------------------------------------------------------------------
# Candidate LOOKS (preview only -- these draw no assets and ship nothing)
# --------------------------------------------------------------------------
# R2.33's screenshot: the geometry lands, and the marks still read as printed ON the
# image rather than painted on the floor. Four things are being asked here, and each is
# a change to the TEXTURE rather than to the renderer, which is why they can be tried
# without touching a shipped constant.
#
#   wear      the interior is one flat alpha, which is the vinyl-sticker tell. Real floor
#             paint is broken -- thin over aggregate, worn where boots go.
#   rim       MARK_RIM is 0.09 of an arm and does not read at all in game.
#   rim_ink   the rim is ink 0, i.e. pure black whatever the route colour, which reads as
#             a hole punched in the glyph rather than a shaded lip.
#   shadow    nothing seats the mark on the ground. It cannot be a second widget (R2.31:
#             a scaled copy of an asymmetric glyph emerges on one edge only), but it CAN
#             be baked outside the outline at ink 0 -- black survives the tint, because
#             SetTextureColor multiplies.
# THE NOISE IS build.py's, not a second copy of it. The preview exists to show what a
# rebuilt texture would look like, and a wear pattern generated by different code would be
# a different pattern -- the one thing this sheet must not do is show grain the shipped
# atlas will not have. Only the AMOUNT is a knob here; bp.wear_field owns the pattern.


def tex_mark_look(bp, R, feather, wear=0.0, rim=None, rim_ink=0.0, body_ink=1.0,
                  shadow=0.0, shadow_w=None, size=256, seed=11):
    """The shipped chevron with any of the four look proposals applied.

    Everything still goes out in build.py's convention -- ink in RGB, coverage in alpha --
    because that is what survives SetTextureColor. The shadow is composited UNDER the
    paint here rather than drawn as a halo at render time, so what the sheet shows is what
    a rebuilt texture would give.
    """
    bp.FEATHER = feather
    if rim is not None:
        bp.MARK_RIM = rim
    hl, hw, ha = R["alen"] * 0.5, R["awide"] * 0.5, R["aw"] * 0.5
    pad = feather * R["aw"]
    # The halo's width in ground metres. mark_alpha's edge ramp reaches pad/2 OUTSIDE the
    # true outline, so passing a fat pad is exactly a soft dilation -- the shape's own
    # distance field, reused, rather than a blur of the picture.
    sw = shadow_w if shadow_w is not None else 0.75 * R["aw"]
    R["SPAD"] = (sw * 0.5) if shadow > 0 else 0.0
    back, fwd, half = shape_box("chevron", R)
    wm = bp.wear_field(size, seed) if wear > 0 else None
    img = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    px = img.load()
    for j in range(size):
        Y = -half + (j + 0.5) / size * (half * 2)
        for i in range(size):
            X = -back + (i + 0.5) / size * (back + fwd)
            av, ink = bp.mark_alpha(X, Y, hl, hw, ha, pad, want_ink=True)
            # THE KEYLINE, remapped at both ends. `ink` is 0 in the rim band and 1 inside,
            # and it MULTIPLIES the route colour, so the two ends are the rim's darkness
            # and the body's. Sliding rim_ink up gives a dark lip instead of a black hole;
            # pulling body_ink down below 1 inverts the whole device into a BRIGHT rim on
            # a slightly deeper body, which is the version that survives dark ground --
            # a black keyline on dark concrete is a black edge on a black floor.
            ink = rim_ink + (body_ink - rim_ink) * ink
            # Wear the paint, not the shadow -- a contact shadow is cast by the mark's
            # outline and does not flake with it.
            if wm is not None:
                # Thin where the noise dips below `thr` and nowhere else, so most of the
                # mark stays solid and the wear reads as scuffing rather than as a
                # texture laid over the whole glyph.
                t = max(0.0, (0.44 - wm[j][i]) / 0.44)
                av *= max(0.0, 1.0 - wear * t ** 1.1)
            if shadow > 0:
                h = bp.mark_alpha(X, Y, hl, hw, ha, sw) * shadow
                fa = av + h * (1 - av)
                ink = (av * ink) / fa if fa > 1e-6 else 0.0
                av = fa
            v = int(round(255 * ink))
            px[i, j] = (v, v, v, int(round(255 * av)))
    return img


# --------------------------------------------------------------------------
# Candidate SHAPES (preview only -- these draw no assets and ship nothing)
# --------------------------------------------------------------------------
# The keystone residual scales with how much DEPTH the glyph's footprint spans, and
# nothing else (R2.31). So the shape question is really a box question, and these exist
# to see what the two cheaper boxes actually look like before any of it is committed to
# build.py. `chevron` is the shipped artwork and comes from build.py as always.
#
#   arrow  a FILLED triangle -- same tip, no interior gap, so it needs no mitre
#          allowance and spans ~40% less depth than the chevron at the same width
#   bar    a plain rung across the path -- spans only its own thickness, which is the
#          least depth any mark can have while still being a mark
def shape_box(kind, R):
    """(back, fwd, half) in mark metres, the box the shape is drawn into and measured in."""
    hl, hw, ha = R["alen"] * 0.5, R["awide"] * 0.5, R["aw"] * 0.5
    # SPAD is the baked shadow's reach outside the outline, and it has to be in the BOX or
    # the halo is drawn outside the rect it was baked into -- i.e. cropped off. Zero
    # unless tex_mark_look put one there, so every other path is untouched.
    pad = R["FPAD"] * R["aw"] + R.get("SPAD", 0.0)
    if kind == "bar":
        return ha + pad, ha + pad, hw + pad
    if kind == "arrow":
        return hl + pad, hl + pad, hw + pad
    if kind in ("disc", "square"):
        # Equal in both axes on purpose: these two exist to show what a footprint with a
        # depth-to-width ratio of 1 costs. A rung's ratio is ~0.2, which is why it wins.
        r = hw * 0.55 + pad
        return r, r, r
    L = math.hypot(2.0 * hl, hw)
    return (hl + ha * hw / L + pad, hl + ha * L / hw + pad, hw + ha * 2.0 * hl / L + pad)


def tex_shape(kind, R, feather, size=192):
    """A convex candidate shape, in the same (ink in RGB, coverage in A) convention.

    Both are convex, so the signed distance is just the smallest distance to an edge --
    positive inside. That gives the feather and the inset keyline in one pass, the same
    two things build.mark_alpha computes for the chevron.
    """
    back, fwd, half = shape_box(kind, R)
    hl, hw, ha = R["alen"] * 0.5, R["awide"] * 0.5, R["aw"] * 0.5
    pad = feather * R["aw"]
    rim = 0.09 * R["aw"]                       # MARK_RIM, the baked keyline
    if kind == "disc":
        # Here to show what the ONE exactly-representable footprint costs when it is
        # fitted to its bounding box like everything else -- which is what the shipped
        # code would do, and is worse than any other candidate. The exact fit needs the
        # projected conic, not the box. See R2.31.
        r = half - pad
        img = Image.new("RGBA", (size, size), (255, 255, 255, 0))
        px = img.load()
        for j in range(size):
            Y = -half + (j + 0.5) / size * (half * 2)
            for i in range(size):
                X = -back + (i + 0.5) / size * (back + fwd)
                d = r - math.hypot(X, Y)
                a = max(0.0, min(1.0, d / pad + 0.5))
                a = a * a * (3 - 2 * a)
                ink = max(0.0, min(1.0, (d - rim) / pad + 0.5))
                ink = ink * ink * (3 - 2 * ink)
                v = int(round(255 * ink))
                px[i, j] = (v, v, v, int(round(255 * a)))
        return img
    if kind == "square":
        s = half - pad
        edges = [(1, 0, s), (-1, 0, s), (0, 1, s), (0, -1, s)]
    elif kind == "bar":
        edges = [(1, 0, ha), (-1, 0, ha), (0, 1, hw), (0, -1, hw)]   # |n.p| <= c
    else:
        # tip at (+hl, 0), base corners at (-hl, +/-hw): the base plus two long edges
        nx_, ny_ = 2.0 * hl, hw
        m = math.hypot(nx_, ny_)
        c = (2.0 * hl * hl + 0.0) / m          # distance from the origin to a long edge
        edges = [(-1.0, 0.0, hl), (nx_ / m, ny_ / m, c), (nx_ / m, -ny_ / m, c)]
    img = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    px = img.load()
    for j in range(size):
        Y = -half + (j + 0.5) / size * (half * 2)
        for i in range(size):
            X = -back + (i + 0.5) / size * (back + fwd)
            d = min(c - (nx * X + ny * Y) for nx, ny, c in edges)
            a = max(0.0, min(1.0, d / pad + 0.5))
            a = a * a * (3 - 2 * a)
            ink = max(0.0, min(1.0, (d - rim) / pad + 0.5))
            ink = ink * ink * (3 - 2 * ink)
            v = int(round(255 * ink))
            px[i, j] = (v, v, v, int(round(255 * a)))
    return img


