class Canvas:
    """Composites textured, tinted, heading-rotated rects the way the UI layer does.

    A heading-rotated static is built in UI units, rotated rigidly about its own
    centre, and only then scaled -- x by UI_KX and again by w/1024, which together are
    exactly h/768, the y factor (see place_strip). So the shape is rotate-then-
    UNIFORM-scale at h/768, while the rect's CENTRE is a position and takes the plain
    UI->screen map. Getting those two different is what makes a preview lie about
    every angle in the picture.
    """

    def __init__(self, base):
        self.img = base
        self.sc = base.size[1] / UI_H            # uniform shape scale
        self.px = base.size[0] / UI_W            # UI x -> screen px, for positions
        self.py = base.size[1] / UI_H

    def blit(self, tex, cx, cy, ln, th, ang, argb):
        a, r, g, b = argb
        if a <= 2:
            return
        w = max(1, int(round(ln * self.sc)))
        h = max(1, int(round(th * self.sc)))
        if w > 6000 or h > 6000:
            return
        spr = tex.resize((w, h), Image.BILINEAR)
        # tint: white artwork times the colour, alpha times the widget's own
        tr, tg, tb, ta = spr.split()
        spr = Image.merge("RGBA", (
            tr.point(lambda v: v * r // 255),
            tg.point(lambda v: v * g // 255),
            tb.point(lambda v: v * b // 255),
            ta.point(lambda v: v * a // 255)))
        spr = spr.rotate(math.degrees(ang), resample=Image.BICUBIC, expand=True)
        x = int(round(cx * self.px - spr.size[0] * 0.5))
        y = int(round(cy * self.py - spr.size[1] * 0.5))
        self.img.alpha_composite(spr, (x, y))


def seg_width(cam, pa, pb, ax, ay, bx, by, ww, wmin, cap):
    """Port of IqmCards:seg_width -- thickness measured from the ground edges."""
    dx, dz = pb[0] - pa[0], pb[2] - pa[2]
    m = math.hypot(dx, dz)
    th = None
    if m > 1e-4:
        hw = ww * 0.5
        nx, nz = -dz / m * hw, dx / m * hw
        mx, my, mz = (pa[0] + pb[0]) * 0.5, (pa[1] + pb[1]) * 0.5, (pa[2] + pb[2]) * 0.5
        lx, ly, ls = cam.project(mx + nx, my, mz + nz)
        rx, ry, rs = cam.project(mx - nx, my, mz - nz)
        if lx is not None and rx is not None and ls > 0 and rs > 0:
            sepx, sepy = (lx - rx) / cam.ui_kx, ly - ry
            ux, uy = (bx - ax) / cam.ui_kx, by - ay
            ul = math.hypot(ux, uy)
            if ul > 1e-4:
                th = abs(sepx * (-uy / ul) + sepy * (ux / ul))
            else:
                th = math.hypot(sepx, sepy)
    if th is None:
        return wmin
    return max(wmin, min(cap, th))


def place_strip(cv, tex, R, ax, ay, bx, by, th, a, rgb, kx, exact=True, over=0.0,
                joint="full"):
    """Port of IqmCards:place_strip -- the body, and the halo copy behind it.

    `joint` is the preview's own knob and has no counterpart in the game yet. The
    shipped rule is `len + th`: extend every strip by a full thickness so consecutive
    segments overlap by half a width at each end and a bend cannot leave an open wedge
    on the outside of the turn. That is sized against the THICKNESS and takes no account
    of the segment's LENGTH -- and at the near end, where a segment is about a metre of
    ground and the stroke is 60-90 px thick, the extension is as long as the segment
    itself. Every other band then gets painted twice (brighter body, and the later
    segment's black halo over the earlier body), which is the ladder this tool made
    visible.

      full   -- the shipped rule, len + th
      capped -- len + min(th, len * JOINT_FRAC): the same overlap wherever it is small
                relative to the segment, clamped where it is not
      none   -- exact length, to see the wedges the overlap exists to close
    """
    dxk, dy = (bx - ax) / kx, by - ay
    ln = max(1e-4, math.hypot(dxk, dy))
    ang = math.atan2(-dy, dxk)
    mx, my = (ax + bx) * 0.5, (ay + by) * 0.5
    if exact or joint == "none":
        length = ln
    elif joint == "capped":
        length = ln + min(th, ln * JOINT_FRAC)
    else:
        length = ln + th
    if over > 0:
        length += over
        h = over * 0.5 / ln
        mx -= (bx - ax) * h
        my -= dy * h
    edge = min(R["EDGE_MAX"], max(R["EDGE_MIN"], th * R["EDGE"]))
    cv.blit(tex, mx, my, length, th + edge * 2, ang, (int(a * R["SHA"]), 0, 0, 0))
    cv.blit(tex, mx, my, length, th, ang, (int(a), rgb[0], rgb[1], rgb[2]))


def place_arms(cv, tex, R, cam, p, ux, uz, a, rgb):
    """Port of IqmCards:place_arms -- a chevron as two ground strips."""
    hl, hw = R["alen"] * 0.5, R["awide"] * 0.5
    nx, nz = -uz, ux
    t1 = (p[0] + ux * hl, p[1], p[2] + uz * hl)
    tx, ty, ts = cam.project(*t1)
    if tx is None or ts <= 0:
        return
    bx0, bz0 = p[0] - ux * hl, p[2] - uz * hl
    for s in (-1, 1):
        t2 = (bx0 + nx * hw * s, p[1], bz0 + nz * hw * s)
        ex, ey, es = cam.project(*t2)
        if ex is None or es <= 0:
            continue
        th = seg_width(cam, t1, t2, tx, ty, ex, ey, R["aw"], R["WMIN"], R["WMAX"])
        place_strip(cv, tex, R, tx, ty, ex, ey, th, a, rgb, cam.ui_kx, exact=True)


def place_mark(cv, tex, R, cam, p, ux, uz, a, rgb, slices=1, shape="chevron", scale=1.0):
    """Port of IqmCards:place_mark -- the chevron as one quad, or as `slices` of one.

    A CUIStatic is always a rotated RECTANGLE; the true projection of the mark's ground
    footprint is a trapezoid. `slices` cuts the footprint across travel and fits each
    piece its own rectangle -- piecewise affine, so the keystone residual falls roughly
    as 1/N. The cost is that adjacent pieces measure their width at their OWN centres
    and so do not agree at the seam. --slices exists to see which is worse.
    """
    # Same box as build.mark_box() and IqmCards:place_mark -- for the chevron, out to the
    # arm's outer corners with L the true tip-to-corner length. shape_box holds all three.
    back, fwd, half = shape_box(shape, R)
    if scale != 1.0:
        back, fwd, half = back * scale, fwd * scale, half * scale
    nx, nz = -uz, ux
    span = back + fwd
    for k in range(slices):
        s0 = -back + span * k / slices
        s1 = -back + span * (k + 1) / slices
        sm = (s0 + s1) * 0.5
        t1 = (p[0] + ux * s0, p[1], p[2] + uz * s0)
        t2 = (p[0] + ux * s1, p[1], p[2] + uz * s1)
        ax, ay, as_ = cam.project(*t1)
        bx, by, bs = cam.project(*t2)
        if ax is None or bx is None or as_ <= 0 or bs <= 0:
            continue
        # THE RECT IS THE PIECE'S TWO PROJECTED AXES, each measured on its own (R2.28) --
        # not seg_width, which projects out the along-axis skew that for a mark IS the
        # shape. The across axis is measured at the piece's own centre, which is exactly
        # what makes neighbouring pieces disagree at the seam.
        cx_, cy_, cz_ = p[0] + ux * sm, p[1], p[2] + uz * sm
        lx, ly, ls = cam.project(cx_ + nx * half, cy_, cz_ + nz * half)
        rx, ry, rs = cam.project(cx_ - nx * half, cy_, cz_ - nz * half)
        dxk, dy = (bx - ax) / cam.ui_kx, by - ay
        ln = math.hypot(dxk, dy)
        cxk = None
        if lx is not None and rx is not None and ls > 0 and rs > 0:
            cxk, cyy = (lx - rx) / cam.ui_kx, ly - ry
            th = math.hypot(cxk, cyy)
        else:
            th = seg_width(cam, t1, t2, ax, ay, bx, by, half * 2, R["WMIN"], R["MCAP"])
        th = min(max(th, R["WMIN"]), R["MCAP"])
        if ln < 1e-4 and cxk is None:
            continue
        # The along axis keeps a floor in PIXELS (R2.30), the same kind of legibility
        # guard WMIN is for a stroke's thickness -- not a fraction of the artwork's
        # aspect, which bound the whole run to one shape and stopped it lying down into
        # the ground. Shared out between the pieces, so N of them floor where one did.
        if ln < R["MLMIN"] / slices:
            ln = R["MLMIN"] / slices
        # The angle from BOTH axes, weighted by how long each projects (R2.28).
        if cxk is not None:
            w1 = dxk * dxk + dy * dy
            w2 = cxk * cxk + cyy * cyy
            a1 = math.atan2(-dy, dxk)
            a2 = math.atan2(-cyy, cxk) - math.pi * 0.5
            if math.cos(a1 - a2) < 0:
                w1 = 0.0
            ang = math.atan2(w1 * math.sin(a1) + w2 * math.sin(a2),
                             w1 * math.cos(a1) + w2 * math.cos(a2))
        else:
            ang = math.atan2(-dy, dxk)
        mx, my = (ax + bx) * 0.5, (ay + by) * 0.5
        # The texture's WIDTH axis is along travel (build.mark_box maps image x to X),
        # so a piece takes the matching vertical band of the artwork -- SetTextureRect
        # in the game, a crop here.
        sub = tex
        if slices > 1:
            w = tex.size[0]
            sub = tex.crop((int(round(w * k / slices)), 0,
                            int(round(w * (k + 1) / slices)), tex.size[1]))
        # No backing copy since R2.26b -- the keyline is baked into the artwork. See the
        # note in IqmCards:place_mark for why a scaled copy could never be concentric.
        cv.blit(sub, mx, my, ln, th, ang, (int(a), rgb[0], rgb[1], rgb[2]))


