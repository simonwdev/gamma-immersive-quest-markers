# Camera
# --------------------------------------------------------------------------
class Camera:
    """A pinhole stand-in for game.world2ui_with_depth.

    World is X/Z ground with Y up, as the game's is. The camera sits at eye height
    above the actor and looks along +X with a downward pitch -- i.e. what you see
    walking a route, which is the only view the route is ever judged in.
    """

    def __init__(self, eye=(0.0, 1.6, 0.0), pitch_deg=-12.0, yaw_deg=0.0,
                 vfov_deg=55.0, out_w=1280, out_h=720):
        self.eye = eye
        self.out_w, self.out_h = out_w, out_h
        p, y = math.radians(pitch_deg), math.radians(yaw_deg)
        # forward, right, up in world space
        self.fwd = (math.cos(p) * math.cos(y), math.sin(p), math.cos(p) * math.sin(y))
        self.right = (-math.sin(y), 0.0, math.cos(y))
        self.up = (-math.sin(p) * math.cos(y), math.cos(p), -math.sin(p) * math.sin(y))
        self.tan_half_v = math.tan(math.radians(vfov_deg) * 0.5)
        self.aspect = out_w / out_h
        # The engine's own aspect correction for rotated statics, from the same
        # expression iqm_core uses: (h/w) / (768/1024).
        self.ui_kx = (out_h / out_w) / (UI_H / UI_W)

    def project(self, x, y, z):
        """world -> (ui_x, ui_y, depth_sign). None when the point is behind the camera.

        Mirrors project_off's contract: the third value is a SIGN in the game (-1
        behind the camera), and callers only ever test `> 0`, so a depth is a
        strictly more informative thing to hand back that still satisfies them.
        """
        dx, dy, dz = x - self.eye[0], y - self.eye[1], z - self.eye[2]
        f = dx * self.fwd[0] + dy * self.fwd[1] + dz * self.fwd[2]
        if f <= 0.001:
            return None, None, -1.0
        r = dx * self.right[0] + dy * self.right[1] + dz * self.right[2]
        u = dx * self.up[0] + dy * self.up[1] + dz * self.up[2]
        ndc_x = (r / f) / (self.tan_half_v * self.aspect)
        ndc_y = (u / f) / self.tan_half_v
        return (ndc_x * 0.5 + 0.5) * UI_W, (0.5 - ndc_y * 0.5) * UI_H, f

    def dist(self, x, y, z):
        dx, dy, dz = x - self.eye[0], y - self.eye[1], z - self.eye[2]
        return math.sqrt(dx * dx + dy * dy + dz * dz)


