def render(cfg, R, nav, bp, out_w, out_h):
    cam = Camera(eye=(0.0, 1.6, getattr(cfg, 'strafe', 0.0) or 0.0),
                 pitch_deg=cfg.pitch, vfov_deg=cfg.fov, out_w=out_w, out_h=out_h)
    path = scene_path(cfg.scene, nav["PATH_STEP"], nav["ARROW_LIFT"])
    verts, vs, chevs, cs = build_draw_list(path, cam, nav, cfg.dist, cfg.gap,
                                          half_phase=getattr(cfg, 'half_phase', False))

    base = ground(cam, out_w, out_h)
    cv = Canvas(base)

    # The two style predicates draw_route uses, same names, same membership.
    glyph_style = cfg.style in ("glyph", "marks")
    strokeless = cfg.style in ("arrows", "marks") or cfg.no_stroke

    strip = tex_strip(bp, cfg.feather)
    arm = tex_strip(bp, cfg.feather, tip=cfg.arm_tip, tail=cfg.arm_tail)
    # The glyph's SHAPE lives in the artwork while its BOX lives in RTE, and build.py says
    # of its MARK_* constants: "These four mirror RTE.alen / awide / aw ... Change one,
    # change both -- a mismatch shows up as the glyph sitting slightly off its own box."
    # Nothing enforces that in the mod, and here it would be worse than unenforced: an
    # --aw sweep would move the box while the picture stayed put, so every panel would be
    # answering a different question from the one asked. So the rule is applied.
    bp.MARK_LEN, bp.MARK_WIDE, bp.MARK_ARM = R["alen"], R["awide"], R["aw"]
    bp.MARK_TAIL = cfg.arm_tail
    shape = getattr(cfg, 'shape', 'chevron')
    if not glyph_style:
        mark = None
    elif shape == 'chevron':
        R["SPAD"] = 0.0
        mark = tex_mark_look(bp, R, cfg.feather,
                             wear=getattr(cfg, 'wear', 0.0) or 0.0,
                             rim=getattr(cfg, 'rim', None),
                             rim_ink=getattr(cfg, 'rim_ink', 0.0) or 0.0,
                             body_ink=getattr(cfg, 'body_ink', 1.0) or 1.0,
                             shadow=getattr(cfg, 'shadow', 0.0) or 0.0,
                             seed=int(getattr(cfg, 'seed', 11) or 11))
    else:
        mark = tex_shape(shape, R, cfg.feather)

    rgb = (int(R.get("route_r", R["r"])), int(R.get("route_g", 196)),
           int(R.get("route_b", 124)))
    if cfg.colour:
        rgb = cfg.colour
    alpha = cfg.alpha

    # Project every vertex once, as draw_route does.
    sx, sy, sd = [], [], []
    for p in verts:
        x, y, d = cam.project(*p)
        sx.append(x)
        sy.append(y)
        sd.append(cam.dist(*p) if x is not None else None)
    drawn = [d for d in sd if d is not None]
    d0 = min(drawn) if drawn else 0.0

    def fade_at(idx, n, d):
        """The two-ended fade: TAIL by position in the run, HEAD/HMIN by camera distance."""
        t = (idx - 1) / (n - 1) if n > 1 else 0.0
        if t > R["FADE"]:
            return 1 - (t - R["FADE"]) / (1 - R["FADE"]) * (1 - R["TAIL"])
        near = ((d if d is not None else 1e9) - d0) / cfg.head
        return cfg.hmin + (1 - cfg.hmin) * max(0.0, near) if near < 1 else 1.0

    n = len(verts)
    for k in range(len(chevs) - 1, -1, -1):
        p, ux, uz, vi = chevs[k]
        cd = cam.dist(*p)
        t = (k) / len(chevs) if len(chevs) > 1 else 0.0
        if t > R["FADE"]:
            f = 1 - (t - R["FADE"]) / (1 - R["FADE"]) * (1 - R["TAIL"])
        else:
            near = (cd - d0) / cfg.head
            f = cfg.hmin + (1 - cfg.hmin) * max(0.0, near) if near < 1 else 1.0
        # THE NEAR CUT-OFF, which this tool did not reproduce until R2.33c -- so it drew
        # marks at the player's feet that the game refuses to draw, and any question about
        # the near field got a confidently wrong answer. Exactly the class of drift the
        # header warns about, in the one constant the near field is entirely about.
        mnear = getattr(cfg, 'mnear', None)
        mnear = R["MNEAR"] if mnear is None else mnear
        mfade = getattr(cfg, 'mfade', None)
        mfade = R["MFADE"] if mfade is None else mfade
        if cd < mnear:
            f = 0.0
        elif cd < mnear + mfade:
            f *= (cd - mnear) / mfade
        # The near TAPER (preview only): shrink the glyph as it approaches, so the
        # footprint spans less depth exactly where the affine fit is worst. 1.0 = off.
        tmin = getattr(cfg, 'taper', 1.0) or 1.0
        sc = 1.0
        if tmin < 1.0:
            u = max(0.0, min(1.0, (cd - mnear) / max(1e-6, 5.0 - mnear)))
            sc = tmin + (1 - tmin) * u
        a = alpha * f
        if True:
            place_mark(cv, mark, R, cam, p, ux, uz, a, rgb, slices=int(getattr(cfg, 'slices', 1) or 1),
                       shape=getattr(cfg, 'shape', 'chevron'), scale=sc)
        else:
            place_arms(cv, arm, R, cam, p, ux, uz, a, rgb)

    return base.convert("RGB")


