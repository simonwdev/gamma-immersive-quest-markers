def ground(cam, w, h, seed=7):
    """Procedural concrete, with a pale patch and a dark one.

    Not decoration: the route's legibility problem is contrast against ground it does
    not control, and a flat grey backdrop flatters a washed-out stroke in a way real
    ground does not. Drawn in WORLD space and projected, so the texture recedes with
    the same perspective the route does and near marks are judged against near ground.
    """
    import random
    rnd = random.Random(seed)
    img = Image.new("RGBA", (w, h), (44, 46, 48, 255))
    dr = ImageDraw.Draw(img)
    # sky/horizon wash above the horizon line
    hz = cam.project(1e5, 0.0, 0.0)[1] or 0
    dr.rectangle([0, 0, w, max(0, int(hz * h / UI_H))], fill=(64, 68, 72, 255))

    def put(x, z, size, col):
        ux, uy, d = cam.project(x, 0.0, z)
        if ux is None or d <= 0.5:
            return
        r = max(1.0, size * 380 / d)
        dr.ellipse([ux * w / UI_W - r, uy * h / UI_H - r * 0.35,
                    ux * w / UI_W + r, uy * h / UI_H + r * 0.35], fill=col)

    # Broad tonal variation first, then grit on top of it. Kept low-contrast and
    # small-featured: the backdrop must not compete with the thing being judged, and a
    # blotchy one makes every stroke look crisper than it is by comparison.
    for _ in range(900):
        x = rnd.uniform(0.5, 80.0)
        z = rnd.uniform(-30.0, 30.0)
        v = rnd.randint(46, 60)
        put(x, z, rnd.uniform(0.35, 1.1), (v, v - 1, v - 3, 255))
    # A deliberately PALE stretch and a deliberately DARK one, across the path. The route
    # has to stay readable on both, and a uniform mid-grey never asks it to.
    for _ in range(1400):
        x = rnd.uniform(9.0, 19.0)
        z = rnd.uniform(-7.0, 7.0)
        v = rnd.randint(88, 104)
        put(x, z, rnd.uniform(0.25, 0.6), (v, v - 1, v - 6, 255))
    for _ in range(1400):
        x = rnd.uniform(26.0, 40.0)
        z = rnd.uniform(-7.0, 7.0)
        v = rnd.randint(24, 34)
        put(x, z, rnd.uniform(0.25, 0.6), (v, v, v + 1, 255))
    for _ in range(4200):
        x = rnd.uniform(0.3, 90.0)
        z = rnd.uniform(-25.0, 25.0)
        v = rnd.randint(30, 92)
        put(x, z, rnd.uniform(0.03, 0.14), (v, v, v - 3, 255))
    return img.filter(ImageFilter.GaussianBlur(0.7))


