# The route geometry (iqm_nav's half)
# --------------------------------------------------------------------------
def scene_path(name, step, lift):
    """A dense point list, PATH_STEP apart, standing in for a solved A* route."""
    pts = []
    if name == "straight":
        n = int(70 / step)
        for i in range(n):
            pts.append((i * step, lift, 0.0))
    elif name == "bend":
        # 14 m out, a 90 degree turn rounded over a couple of metres (what smooth()
        # leaves), then away to the right. The corner is the case vertex placement
        # exists for, so it is the case worth looking at.
        d = 0.0
        while d < 14.0:
            pts.append((d, lift, 0.0))
            d += step
        for k in range(1, 13):
            t = k / 12.0
            ang = t * math.pi * 0.5
            cx, cz = 14.0, 3.0
            pts.append((cx + 3.0 * math.sin(ang) - 0.0, lift, cz - 3.0 * math.cos(ang)))
        d = 0.0
        while d < 45.0:
            pts.append((17.0, lift, 3.0 + d))
            d += step
    elif name == "curve":
        d = 0.0
        while d < 70.0:
            pts.append((d, lift, 6.0 * math.sin(d / 22.0)))
            d += step
    else:
        raise SystemExit("preview: unknown scene %r" % name)
    return pts


def build_draw_list(path, cam, nav, draw_m, gap_m, half_phase=False):
    """Port of iqm_nav.build_draw_list: vertices by turn/allowance, chevrons by arclength.

    Reduced to what the picture needs -- no cursor, no occlusion, no PHASE_ABS branch,
    and the trim comes straight from NEAR_TRIM (0 since R2.25) rather than being walked
    off a cursor. The vertex SPACING rule is the part that matters here, because it sets
    how thickness steps from one segment to the next.
    """
    seg_div, seg_min, seg_max = nav["SEG_DIV"], nav["SEG_MIN"], nav["SEG_MAX"]
    turn_tol, max_draw, max_chev = nav["TURN_TOL"], int(nav["MAX_DRAW"]), int(nav["MAX_CHEV"])

    def seg_allow(p):
        s = cam.dist(*p) / seg_div
        return max(seg_min, min(seg_max, s))

    start, trim = 0, 0.0
    trim_max = min(nav["NEAR_TRIM"], draw_m * nav["TRIM_FRAC"])
    while start < len(path) - 2:
        p = path[start]
        if cam.dist(*p) >= nav["NEAR_TRIM"]:
            break
        q = path[start + 1]
        seg = math.hypot(q[0] - p[0], q[2] - p[2])
        if trim + seg > trim_max:
            break
        trim, start = trim + seg, start + 1

    verts, vs = [path[start]], [0.0]
    chevs, cs = [], []
    # R2.25: the first chevron is ON the drawn start. HALF_PHASE adds one more at half a
    # gap (R2.33c), which is the near hole's actual shape: marks sit at k * gap from the
    # actor, so at the default spacing there is simply no paint between his feet and 3 m.
    sched = [0.0] + ([gap_m * 0.5] if half_phase else [])
    sched += [gap_m * k for k in range(1, max_chev + 2)]
    si = 0
    chev_at = sched[0]
    acc, vacc, turn = 0.0, 0.0, 0.0
    allow = seg_allow(path[start])
    emitted, last = start, start
    pdx = pdz = None

    for i in range(start + 1, len(path)):
        if len(verts) >= max_draw:
            break
        a, b = path[i - 1], path[i]
        dx, dz = b[0] - a[0], b[2] - a[2]
        seg = math.hypot(dx, dz)
        if acc + seg > draw_m:
            break
        if seg > 1e-4:
            ux, uz = dx / seg, dz / seg
            if pdx is not None:
                dot = pdx * ux + pdz * uz
                if dot < 1:
                    turn += 1 - dot
        if turn >= turn_tol or vacc + seg > allow:
            if emitted != i - 1:
                verts.append(path[i - 1])
                vs.append(acc)
                emitted, vacc, turn = i - 1, 0.0, 0.0
                allow = seg_allow(path[i - 1])
        if seg > 1e-4:
            while len(chevs) < max_chev and chev_at <= acc + seg:
                t = (chev_at - acc) / seg if seg > 1e-6 else 0.0
                chevs.append(((a[0] + dx * t, a[1] + (b[1] - a[1]) * t, a[2] + dz * t),
                              ux, uz, max(1, len(verts))))
                cs.append(chev_at)
                si += 1
                if si >= len(sched):
                    break
                chev_at = sched[si]
            pdx, pdz = ux, uz
        acc, vacc = acc + seg, vacc + seg
        last = i
    if len(verts) < max_draw and last > start and emitted != last:
        verts.append(path[last])
        vs.append(acc)
    return verts, vs, chevs, cs


